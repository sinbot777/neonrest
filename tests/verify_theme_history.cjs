const assert = require('node:assert/strict');
const {ThemeEditHistory} = require('../static/js/theme-history.js');
const day = {css: 'day', null_bg_color: true, logo: '/static/logo.png'};
const h = new ThemeEditHistory(day, 3);
assert.equal(h.dirty, false);
assert.equal(h.canUndo, false);
h.record({...day, css: 'new day'});
h.record({...day, css: 'new day', null_bg_color: false});
assert.equal(h.dirty, true);
assert.deepEqual(h.undo(), {...day, css: 'new day'});
assert.deepEqual(h.undo(), day);
assert.equal(h.dirty, false);
assert.equal(h.redo().css, 'new day');
h.record({...day, css: 'different edit'});
assert.equal(h.canRedo, false, 'New edit drops redo branch');
assert.deepEqual(h.discard(), day);
assert.equal(h.dirty, false);
assert.equal(h.undo().css, 'different edit', 'Discard itself is undoable');
for (let i=0;i<100;i++) h.record({...day, css: String(i)});
assert.equal(h.states.length, 3, 'History memory bounded');
assert.deepEqual(h.discard(), day, 'Loaded baseline survives history pruning');
const night = new ThemeEditHistory({css:'night'});
assert.equal(night.canUndo, false);
assert.equal(night.current().css, 'night', 'Modes do not share unsaved history');
console.log('Theme unsaved undo/redo/discard/branching/bounds/mode isolation passed');
